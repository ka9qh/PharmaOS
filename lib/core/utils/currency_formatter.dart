// تنسيق عرض المبالغ المالية بشكل موحد - يقرأ رمز العملة من الإعدادات (Phase 9).
//
// ⚠️ ملاحظة صادقة: هذا الملف الآن قابل للاستخدام فعليًا ومربوط بالإعدادات،
// لكن أغلب الشاشات القديمة (POS, Inventory, Reports وغيرها من قبل هذه
// المرحلة) لا تزال تستخدم النص الثابت "ريال" مباشرة بدلاً من استدعاء هذا
// الملف - استبدالها في عشرات الملفات مهمة منفصلة لم تُنفَّذ بعد بالكامل.
// أي شاشة جديدة من الآن فصاعدًا يجب أن تستخدم CurrencyFormatter.format() بدلاً
// من كتابة "ريال" مباشرة.

class CurrencyFormatter {
  CurrencyFormatter._();

  /// يُحدَّث من SettingsRepository عند بدء التطبيق وعند أي تعديل للإعدادات.
  /// القيمة الافتراضية "ريال" تبقى فعالة حتى لو لم تُحمَّل الإعدادات بعد.
  static String currentSymbol = 'ريال';

  static String format(num amount) {
    return '${amount.toStringAsFixed(0)} $currentSymbol';
  }
}
